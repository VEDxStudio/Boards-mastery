// Helper to get all chapters flat
export function getAllChapters(): Subject['sections'][0]['chapters'] {
  const chapters: Subject['sections'][0]['chapters'] = [];
  for (const subject of CBSE_SYLLABUS) {
    for (const section of subject.sections) {
      for (const chapter of section.chapters) {
        chapters.push(chapter);
      }
    }
  }
  return chapters;
}

// Map of chapter ID to Subject
export const CHAPTER_SUBJECT_MAP: Record<string, string> = {};
for (const sub of CBSE_SYLLABUS) {
  for (const sec of sub.sections) {
    for (const ch of sec.chapters) {
      CHAPTER_SUBJECT_MAP[ch.id] = sub.id;
    }
  }
}
